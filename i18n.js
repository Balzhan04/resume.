const supportedLanguages = ['kk', 'en', 'ru'];
let currentLang = 'kk';

function translatePage(lang) {
  currentLang = supportedLanguages.includes(lang) ? lang : 'kk';
  window.currentLang = currentLang;
  document.documentElement.lang = currentLang;

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (translations[currentLang][key]) {
      el.textContent = translations[currentLang][key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (translations[currentLang][key]) {
      el.setAttribute('placeholder', translations[currentLang][key]);
    }
  });

  document.querySelectorAll('.lang-btn').forEach((btn) => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === currentLang);
  });

  window.renderProjects?.(currentLang);
  window.updateTypedText?.(currentLang);
}

document.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('.lang-btn').forEach((btn) => {
    btn.addEventListener('click', () => translatePage(btn.getAttribute('data-lang')));
  });
  translatePage(currentLang);
});
